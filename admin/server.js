/**
 * TRESA Atelier — Local Admin Server
 * 
 * Features:
 * - Serves Visual Admin Studio at http://localhost:4000/admin
 * - Reads & Writes data/products.js (and data/products.json)
 * - Auto-converts uploaded images (JPG, PNG, TIFF, etc.) to optimized WebP via Sharp
 * - Serves project assets & pages for immediate live preview
 */

const express = require('express');
const multer = require('multer');
const sharp = require('sharp');
const fs = require('fs');
const path = require('path');

const app = express();
const PORT = process.env.PORT || 4000;

// Root project directory
const ROOT_DIR = path.resolve(__dirname, '..');
const PRODUCTS_JS_PATH = path.join(ROOT_DIR, 'data', 'products.js');
const PRODUCTS_JSON_PATH = path.join(ROOT_DIR, 'data', 'products.json');
const ASSETS_PRODUCTS_DIR = path.join(ROOT_DIR, 'assets', 'products');

// Ensure necessary directories exist
['cutlery', 'plates', 'placemats'].forEach(cat => {
  const dir = path.join(ASSETS_PRODUCTS_DIR, cat);
  if (!fs.existsSync(dir)) {
    fs.mkdirSync(dir, { recursive: true });
  }
});

// Middleware
app.use(express.json({ limit: '25mb' }));
app.use(express.urlencoded({ extended: true, limit: '25mb' }));

// Multer memory storage (processes in memory before sharp conversion)
const upload = multer({
  storage: multer.memoryStorage(),
  limits: { fileSize: 35 * 1024 * 1024 } // 35 MB max input
});

/**
 * Helper: Read products catalog from data/products.js
 */
function readProductsCatalog() {
  try {
    delete require.cache[require.resolve(PRODUCTS_JS_PATH)];
    const products = require(PRODUCTS_JS_PATH);
    if (Array.isArray(products)) {
      return products;
    }
  } catch (err) {
    console.warn('[Server] Error requiring products.js, attempting JSON fallback:', err.message);
  }

  // Fallback to products.json if available
  if (fs.existsSync(PRODUCTS_JSON_PATH)) {
    try {
      const raw = fs.readFileSync(PRODUCTS_JSON_PATH, 'utf8');
      return JSON.parse(raw);
    } catch (e) {
      console.error('[Server] Error reading products.json:', e);
    }
  }
  return [];
}

/**
 * Helper: Save products catalog to data/products.js and data/products.json
 */
function saveProductsCatalog(products) {
  const jsonContent = JSON.stringify(products, null, 2);

  // 1. Write pure products.json for tool compatibility
  fs.writeFileSync(PRODUCTS_JSON_PATH, jsonContent, 'utf8');

  // 2. Write products.js with the robust universal wrapper
  const jsContent = `/**
 * TRESA Atelier — Centralized Product Catalog
 * Auto-generated by TRESA Catalog Studio
 * Last updated: ${new Date().toISOString()}
 */

(function(global) {
  'use strict';

  var PRODUCTS = ${jsonContent};

  // Expose as global for standalone browser script loading
  global.TRESA_PRODUCTS = PRODUCTS;

  // Support ES Module or CommonJS export if bundled or required in Node
  if (typeof module !== 'undefined' && module.exports) {
    module.exports = PRODUCTS;
  }
})(typeof window !== 'undefined' ? window : this);
`;

  fs.writeFileSync(PRODUCTS_JS_PATH, jsContent, 'utf8');
}

// ─── API ROUTES ───

/**
 * GET /api/products
 * Fetch all products
 */
app.get('/api/products', (req, res) => {
  try {
    const products = readProductsCatalog();
    res.json({ success: true, count: products.length, products });
  } catch (err) {
    res.status(500).json({ success: false, error: err.message });
  }
});

/**
 * POST /api/products
 * Overwrite full products catalog (used for save, reorder, batch updates)
 */
app.post('/api/products', (req, res) => {
  try {
    const { products } = req.body;
    if (!Array.isArray(products)) {
      return res.status(400).json({ success: false, error: 'products must be an array' });
    }

    saveProductsCatalog(products);
    console.log(`[Server] Saved ${products.length} products to data/products.js and data/products.json`);
    res.json({ success: true, count: products.length, message: 'Catalog saved successfully' });
  } catch (err) {
    console.error('[Server] Failed to save products:', err);
    res.status(500).json({ success: false, error: err.message });
  }
});

/**
 * POST /api/upload
 * Seamless auto-conversion to optimized WebP via Sharp
 */
app.post('/api/upload', upload.single('image'), async (req, res) => {
  try {
    if (!req.file) {
      return res.status(400).json({ success: false, error: 'No image file uploaded' });
    }

    const category = (req.body.category || 'cutlery').toLowerCase().trim();
    const safeCategory = ['cutlery', 'plates', 'placemats'].includes(category) ? category : 'cutlery';
    const targetDir = path.join(ASSETS_PRODUCTS_DIR, safeCategory);

    if (!fs.existsSync(targetDir)) {
      fs.mkdirSync(targetDir, { recursive: true });
    }

    // Generate safe WebP filename
    const baseSlug = (req.body.slug || 'product').toLowerCase().replace(/[^a-z0-9_-]/g, '-').replace(/-+/g, '-');
    const indexSuffix = req.body.index ? `-${String(req.body.index).padStart(2, '0')}` : `-${Date.now().toString().slice(-4)}`;
    const finalFilename = `${baseSlug}${indexSuffix}.webp`;
    const finalFilePath = path.join(targetDir, finalFilename);

    const originalSize = req.file.size;

    // Sharp processing pipeline:
    // 1. rotate() -> auto-orient based on EXIF orientation tag
    // 2. resize() -> constrain to max 1600px width/height while maintaining aspect ratio
    // 3. webp() -> high-fidelity 82% quality compression, effort 6 (optimum speed/ratio)
    const pipeline = sharp(req.file.buffer)
      .rotate()
      .resize({
        width: 1600,
        height: 1600,
        fit: 'inside',
        withoutEnlargement: true
      })
      .webp({
        quality: 82,
        effort: 6
      });

    const info = await pipeline.toFile(finalFilePath);

    const relativeWebPath = `./assets/products/${safeCategory}/${finalFilename}`;

    console.log(`[Server] Converted ${req.file.originalname} (${(originalSize / 1024).toFixed(1)} KB) -> ${finalFilename} (${(info.size / 1024).toFixed(1)} KB, -${Math.round((1 - info.size / originalSize) * 100)}%)`);

    res.json({
      success: true,
      filename: finalFilename,
      path: relativeWebPath,
      category: safeCategory,
      originalSize: originalSize,
      newSize: info.size,
      width: info.width,
      height: info.height,
      savedPercent: Math.round((1 - info.size / originalSize) * 100)
    });
  } catch (err) {
    console.error('[Server] Upload & WebP conversion failed:', err);
    res.status(500).json({ success: false, error: err.message });
  }
});

/**
 * GET /api/media
 * List all available product image files in assets/products
 */
app.get('/api/media', (req, res) => {
  try {
    const media = [];
    ['cutlery', 'plates', 'placemats'].forEach(cat => {
      const catDir = path.join(ASSETS_PRODUCTS_DIR, cat);
      if (fs.existsSync(catDir)) {
        const files = fs.readdirSync(catDir);
        files.forEach(file => {
          if (/\.(webp|jpg|jpeg|png|svg)$/i.test(file)) {
            const fullPath = path.join(catDir, file);
            const stat = fs.statSync(fullPath);
            media.push({
              category: cat,
              filename: file,
              path: `./assets/products/${cat}/${file}`,
              size: stat.size,
              updatedAt: stat.mtime
            });
          }
        });
      }
    });

    res.json({ success: true, count: media.length, media });
  } catch (err) {
    res.status(500).json({ success: false, error: err.message });
  }
});

// ─── STATIC SERVING ───

// Serve Admin UI static files
app.use('/admin', express.static(path.join(ROOT_DIR, 'admin')));

// Serve assets directory so images load properly in admin & frontend
app.use('/assets', express.static(path.join(ROOT_DIR, 'assets')));

// Serve root project directory (enables testing index.html, products.html, about.html directly on port 4000)
app.use(express.static(ROOT_DIR));

// Redirect root to /admin if someone opens http://localhost:4000/
app.get('/admin', (req, res) => {
  res.sendFile(path.join(ROOT_DIR, 'admin', 'index.html'));
});

// Start Server
app.listen(PORT, () => {
  console.log(`\n======================================================`);
  console.log(`  ✦ TRESA Atelier — Local Catalog Studio ✦`);
  console.log(`  ----------------------------------------------------`);
  console.log(`  Admin Dashboard:  http://localhost:${PORT}/admin`);
  console.log(`  Live Storefront:  http://localhost:${PORT}/index.html`);
  console.log(`  Auto-WebP:        ACTIVE (Sharp 0.33.5)`);
  console.log(`======================================================\n`);
});
